import { O } from "@mobily/ts-belt";
import { describe, expect, it } from "vitest";
import { importDate } from "../src/import-date";

describe("importDate", () => {
	it.each([
		["2023-09-30", "2023-09-30T00:00:00.000Z"],
		["2024-02-29", "2024-02-29T00:00:00.000Z"],
		["2023-09-30T10:20:30Z", "2023-09-30T10:20:30.000Z"],
		["2023-09-30T10:20:30.5+07:00", "2023-09-30T03:20:30.500Z"],
		["09/30/2023", "2023-09-30T00:00:00.000Z"],
		["9/5/2023", "2023-09-05T00:00:00.000Z"],
		["02/29/2024", "2024-02-29T00:00:00.000Z"],
		[" 01/02/2023 ", "2023-01-02T00:00:00.000Z"],
		[new Date("2023-09-30T00:00:00.000Z"), "2023-09-30T00:00:00.000Z"],
	])("reads %j", (value, iso) => {
		expect(importDate(value)).toEqual(O.Some(iso));
	});

	it.each([
		"",
		"2023-13-01",
		"2023-02-30",
		"2023-02-29",
		"02/30/2023",
		"02/29/2023",
		"00/10/2023",
		"0099-12-31",
		"2023-09-30T10:00Z",
		"2023-09-30 10:00:00",
		"13/01/2023",
		"30/09/2023",
		"2023-09-30T25:00:00Z",
		"9/5/23",
		"09/30/20233",
		"2023-09-30T10:00:00",
		"yesterday",
		new Date("x"),
		20230930,
		null,
		undefined,
	])("refuses %j", (value) => {
		expect(importDate(value)).toEqual(O.None);
	});
});
